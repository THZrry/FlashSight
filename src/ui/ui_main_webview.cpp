int run_webview_ui(FsApi* api) {
  webview_t w = webview_create(0, nullptr);
  if (!w) {
    std::fprintf(stderr,
                 "webview_create failed (WebView2 Runtime missing?)\n");
    return 1;
  }
  webview_set_title(w, "FlashSight");
  webview_set_size(w, 1280, 820, WEBVIEW_HINT_NONE);

  // ORDER MATTERS: webview_init registers a document-creation script, so the
  // glue has to be installed BEFORE the first document is loaded. Doing it the
  // other way round leaves every call hitting an undefined `__fsDomCall` and
  // the window stays blank.
  webview_install_glue(w);
  webview_set_html(w, shell_html().c_str());

  IDom* dom = make_webview_dom(w);
  NativeBackend backend(api);  // in-process FsApi calls, no HTTP
  int rc = 0;
  {
    AppState st = AppState::make();
    UiApp ui(*dom, st, &backend);
    ui.mount();

    // Diagnostics: inspect the live page + simulate a click, so a "nothing
    // happens" report can be told apart from "the adapter never bound".
    if (std::getenv("FS_UI_WEBVIEW_DEBUG")) {
      webview_dispatch(w, [](webview_t wv, void* ud) {
        webview_debug_probe(wv, ud);
      }, dom);
    }

    // Backend events + the terminal poller. webview has no timer of its own, so
    // a C++ thread drives them and hops onto the UI thread through
    // webview_dispatch (the only thread-safe way to touch the DOM here).
    std::atomic<bool> running(true);
    std::thread ticker([&]() {
      while (running.load()) {
        std::this_thread::sleep_for(std::chrono::milliseconds(50));
        webview_dispatch(w, [](webview_t wv, void* ud) {
          UiApp* app = static_cast<UiApp*>(ud);
          app->pump();
          app->tick_terminal();
        }, &ui);
      }
    });

    rc = webview_run(w);  // blocks until the window closes

    running.store(false);
    ticker.join();
  }

  delete dom;
  webview_destroy(w);
  return rc;
}

