std::string asset(const char* name) {
  const std::vector<assets::Asset>& files = assets::kFiles();
  for (size_t i = 0; i < files.size(); ++i) {
    if (std::strcmp(files[i].name, name) == 0) {
      return std::string(reinterpret_cast<const char*>(files[i].data),
                         files[i].size);
    }
  }
  return std::string();
}

std::string base64(const std::string& raw) {
  static const char* kAlphabet =
      "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  std::string out;
  out.reserve(((raw.size() + 2) / 3) * 4);
  size_t i = 0;
  while (i + 2 < raw.size()) {
    unsigned int v = (static_cast<unsigned char>(raw[i]) << 16) |
                     (static_cast<unsigned char>(raw[i + 1]) << 8) |
                     static_cast<unsigned char>(raw[i + 2]);
    out += kAlphabet[(v >> 18) & 63];
    out += kAlphabet[(v >> 12) & 63];
    out += kAlphabet[(v >> 6) & 63];
    out += kAlphabet[v & 63];
    i += 3;
  }
  if (i + 1 == raw.size()) {
    unsigned int v = static_cast<unsigned char>(raw[i]) << 16;
    out += kAlphabet[(v >> 18) & 63];
    out += kAlphabet[(v >> 12) & 63];
    out += "==";
  } else if (i + 2 == raw.size()) {
    unsigned int v = (static_cast<unsigned char>(raw[i]) << 16) |
                     (static_cast<unsigned char>(raw[i + 1]) << 8);
    out += kAlphabet[(v >> 18) & 63];
    out += kAlphabet[(v >> 12) & 63];
    out += kAlphabet[(v >> 6) & 63];
    out += '=';
  }
  return out;
}

// Replace `url("fa-solid-900.woff2")` in the Font Awesome sheet with a data:
// URI, because the document has no base URL to resolve it against.
std::string inline_font(const std::string& fa_css, const std::string& woff2) {
  const std::string needle = "url(\"fa-solid-900.woff2\")";
  size_t at = fa_css.find(needle);
  if (at == std::string::npos || woff2.empty()) return fa_css;
  std::string uri = "url(\"data:font/woff2;base64," + base64(woff2) + "\")";
  std::string out = fa_css;
  out.replace(at, needle.size(), uri);
  return out;
}

std::string shell_html() {
  std::string css = asset("style.css");
  std::string fa = inline_font(asset("icons/fa-subset.css"),
                               asset("icons/fa-solid-900.woff2"));
  std::string icons = asset("icons/icons.css");
  if (css.empty()) {
    std::fprintf(stderr, "warning: style.css missing from the embedded assets\n");
  }
  std::string html;
  html += "<!DOCTYPE html><html><head><meta charset=\"utf-8\">";
  html += "<title>FlashSight</title><style>";
  html += css;
  html += "\n";
  html += fa;
  html += "\n";
  html += icons;
  html += "</style></head><body><div id=\"fs-root\"></div></body></html>";
  return html;
}

// The exe resource gives Explorer its icon, but WebView2's top-level window
// uses its own class icon. Apply it once after create and once from the message
// loop (WebView2 may replace the class icon during its own initialization).
void apply_window_icon(webview_t w) {
#ifdef _WIN32
  if (HWND hwnd = static_cast<HWND>(webview_get_window(w))) {
    HICON icon = static_cast<HICON>(
        ::LoadIconW(::GetModuleHandleW(nullptr), MAKEINTRESOURCEW(1)));
    if (icon) {
      ::SendMessageW(hwnd, WM_SETICON, ICON_BIG, reinterpret_cast<LPARAM>(icon));
      ::SendMessageW(hwnd, WM_SETICON, ICON_SMALL, reinterpret_cast<LPARAM>(icon));
    }
  }
#else
  (void)w;
#endif
}

