// ui_main_webview.cpp - Desktop entry: webview window + WebViewDom + UiApp.
//
// The desktop counterpart of ui_main_wasm.cpp. The UI itself is the SAME
// C++ (UiApp / VNode diff / components) - only the bottom layer differs:
//
//   Web  (wasm)     : browser tab  + WasmDom (emscripten/val)
//   Desktop(webview): native window + WebViewDom (webview + injected JS glue)
//   Desktop(WhaleUI): native window + WhaleDom (WhaleUI's own renderer)
//
// Everything the app needs from the DOM goes through IDom, so this file only
// has to: build the shell HTML, hand the stylesheets to the page, and run the
// event loop.
//
// STATIC ASSETS ARE EMBEDDED. `webview_set_html` navigates to a data-ish
// document (NavigateToString), which has no base URL - relative <link href>
// and url() references cannot resolve. So the stylesheets and the icon font
// are inlined into the document:
//
//   * web/style.css          -> <style>
//   * web/icons/fa-subset.css-> <style>
//   * web/icons/icons.css    -> <style>   (icons are inline SVG data URIs)
//   * web/icons/fa-solid-900.woff2 -> @font-face src as a data: URI
//
// The bytes come from the generated ui_assets_gen.hpp (the same header the
// browser build serves over HTTP), so a Desktop build embeds exactly what a
// Web build serves.
