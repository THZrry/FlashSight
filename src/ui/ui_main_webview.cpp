int run_webview_ui(FsApi* api) {
  webview_t w = webview_create(0, nullptr);
  if (!w) {
    std::fprintf(stderr,
                 "webview_create failed (WebView2 Runtime missing?)\n");
    return 1;
  }
  webview_set_title(w, "FlashSight");
  webview_set_size(w, 1280, 820, WEBVIEW_HINT_NONE);
  apply_window_icon(w);

  // ORDER MATTERS: webview_init registers a document-creation script, so the
  // glue has to be installed BEFORE the first document is loaded. Doing it the
  // other way round leaves every call hitting an undefined `__fsDomCall` and
  // the window stays blank.
  webview_install_glue(w);
  webview_set_html(w, shell_html().c_str());
  // Re-apply once the WebView2 message loop is running.
  webview_dispatch(w, [](webview_t wv, void*) { apply_window_icon(wv); },
                   nullptr);

  IDom* dom = make_webview_dom(w);
  NativeBackend backend(api);  // in-process FsApi calls, no HTTP
  int rc = 0;
  {
    AppState st = AppState::make();
    UiApp ui(*dom, st, &backend);
    ui.mount();

    // Diagnostics: inspect the live page + simulate a click, so a "nothing
    // happens" report can be told apart from "the adapter never bound".
    if (std::getenv("FS_UI_WEBVIEW_DEBUG")) {
      webview_dispatch(w, [](webview_t wv, void* ud) {
        webview_debug_probe(wv, ud);
      }, dom);
    }

    // Backend events + the terminal poller. webview has no timer of its own, so
    // a C++ thread drives them and hops onto the UI thread through
    // webview_dispatch (the only thread-safe way to touch the DOM here).
    //
    // *** THE ALIVE FLAG IS THE POINT. *** A dispatched callback sits on the
    // webview's message loop and may run AFTER this scope ends: `webview_run`
    // returns when the window closes, but a task posted moments earlier can still
    // be queued. It used to capture `&ui` directly, so it could run against a
    // destroyed UiApp and during window teardown - the "Failed to unregister class
    // Chrome_WidgetWin_0" crash the user hit. Every dispatched task now checks a
    // shared flag first.
    struct PumpCtx {
      UiApp* app = nullptr;
      // Captured BY VALUE by the dispatch lambda below: reading through a pointer
      // to a stack object would be the same use-after-free we are fixing.
      std::shared_ptr<std::atomic<bool> > alive;
    };
    std::shared_ptr<std::atomic<bool> > alive =
        std::make_shared<std::atomic<bool> >(true);
    PumpCtx ctx;
    ctx.app = &ui;
    ctx.alive = alive;
    std::atomic<bool> running(true);
    std::thread ticker([&]() {
      while (running.load()) {
        std::this_thread::sleep_for(std::chrono::milliseconds(50));
        if (!alive->load()) return;
        webview_dispatch(w, [](webview_t wv, void* ud) {
          (void)wv;
          PumpCtx* c = static_cast<PumpCtx*>(ud);
          // A stale task must not touch the app OR the flag object: if the
          // dispatch runs after this function returned, even `c` is suspect - so
          // the flag is read through the pointer the ctx itself carries and the
          // shutdown path clears it before the ctx goes away (see below).
          if (!c || !c->app) return;
          if (c->alive && !c->alive->load()) return;
          c->app->pump();
          c->app->tick_terminal();
          // Resource log: one line every 30 s with the handle count and the
          // sizes of everything the UI keeps in memory. ON BY DEFAULT (a line
          // every 30 s is nothing) because the freeze this exists for happens
          // while nobody is watching - an opt-in flag means the next incident
          // has no evidence again. FS_RES_LOG=0 turns it off. Written to
          // %TEMP%\flashsight_res.log.
          {
            const char* res_env = std::getenv("FS_RES_LOG");
            const bool res_on = !res_env || std::strcmp(res_env, "0") != 0;
            static int64_t last_log = 0;
            static int64_t last_pump_ms = 0;
            int64_t now = static_cast<int64_t>(
                std::chrono::duration_cast<std::chrono::milliseconds>(
                    std::chrono::steady_clock::now().time_since_epoch()).count());
            if (res_on && now - last_log >= 30000) {
              last_log = now;
              // Handle count is a Windows diagnostic. Linux/macOS still write
              // the [res] line (DOM/memory/auto state) with handles=0 instead
              // of failing to compile on DWORD/GetProcessHandleCount.
              unsigned long handles = 0;
#ifdef _WIN32
              DWORD win_handles = 0;
              if (::GetProcessHandleCount(::GetCurrentProcess(), &win_handles)) {
                handles = static_cast<unsigned long>(win_handles);
              }
              const char* tmp = std::getenv("TEMP");
              std::string path = std::string(tmp && *tmp ? tmp : ".") +
                                 "\\flashsight_res.log";
#else
              const char* tmp = std::getenv("TMPDIR");
              std::string path = std::string(tmp && *tmp ? tmp : "/tmp") +
                                 "/flashsight_res.log";
#endif
              if (FILE* f = std::fopen(path.c_str(), "a")) {
                std::fprintf(f, "[res] %lld %s handles=%lu pump_gap_ms=%lld\n",
                             static_cast<long long>(now / 1000),
                             c->app->debug_stats().c_str(),
                             static_cast<unsigned long>(handles),
                             static_cast<long long>(last_pump_ms ? now - last_pump_ms : 0));
                std::fclose(f);
              }
            }
            last_pump_ms = now;
          }
        }, &ctx);
      }
    });

    rc = webview_run(w);  // blocks until the window closes

    // Order matters. The ticker stops first so it posts nothing new; the flag is
    // cleared next so tasks ALREADY queued become no-ops; only then does the ctx
    // go out of scope. Tasks that drain during webview_destroy below therefore see
    // a null app and return.
    running.store(false);
    ticker.join();
    alive->store(false);
    ctx.app = nullptr;
  }

  delete dom;
  webview_destroy(w);
  return rc;
}

