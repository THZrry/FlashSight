#!/usr/bin/env python3
"""Generate web/icons/fa-subset.css + the WOFF2 font it needs.

Why a subset: the packaged build serves everything from inside the exe and
WhaleUI cannot fetch from the network, so the icon font must be local. Font
Awesome's full CSS + font is ~600 KB; we only use a few dozen icons, so this
script keeps just those rules and the WOFF2 file.

Usage:
  1. download the upstream CSS + font once (any CDN), e.g.
       curl -o /tmp/fa-all.min.css \\
         https://unpkg.com/@fortawesome/fontawesome-free@6.5.2/css/all.min.css
       curl -o web/icons/fa-solid-900.woff2 \\
         https://unpkg.com/@fortawesome/fontawesome-free@6.5.2/webfonts/fa-solid-900.woff2
  2. python tools/make_fa_subset.py /tmp/fa-all.min.css

Licenses: icons CC BY 4.0, font SIL OFL 1.1, code MIT (Fonticons, Inc.).
"""
import io
import os
import re
import sys

# Icons the UI actually uses (comp::icon_text_button + terminal/settings rows).
WANTED = [
    'paperclip', 'folder-open', 'folder', 'terminal', 'robot', 'diagram-project',
    'code-branch', 'gear', 'sliders', 'magnifying-glass', 'xmark', 'plus',
    'minus', 'chevron-right', 'chevron-down', 'chevron-left', 'arrow-up',
    'arrow-left', 'play', 'pause', 'stop', 'rotate', 'rotate-left', 'paper-plane',
    'copy', 'check', 'triangle-exclamation',
    'circle-info', 'trash', 'pen', 'floppy-disk', 'bolt', 'clock', 'list-check',
    'comments', 'file-lines', 'bars', 'ellipsis', 'circle-notch', 'spinner',
    'right-from-bracket', 'plug', 'server', 'wand-magic-sparkles', 'shield-halved',
]

# Codepoints for icons we need whose upstream rule may be missing or an alias
# that the selector parse does not recognise. Keeping them here means the subset
# stays reproducible without the upstream CSS file (the shipped WOFF2 is the
# complete solid font, so any of its glyphs can be referenced).
FALLBACK = {
    'pause': '\\f04c',
    'rotate-left': '\\f2ea',
    'paper-plane': '\\f1d8',
}

OUT_CSS = os.path.join('web', 'icons', 'fa-subset.css')


def main():
    if len(sys.argv) < 2:
        sys.stderr.write(__doc__)
        return 2
    css = io.open(sys.argv[1], encoding='utf-8', errors='replace').read()

    # Rules look like ".fa-a:before,.fa-b:before{content:"\f123"}"; parse every
    # comma-separated selector so aliases and shared rules are both picked up.
    found = {}
    for selectors, body in re.findall(r'([^{}]+)\{([^}]*)\}', css):
        m = re.search(r'content:"(\\[0-9a-fA-F]+)"', body)
        if not m:
            continue
        for sel in selectors.split(','):
            sel = sel.strip()
            mm = re.match(r'^\.fa-([a-z0-9-]+):before$', sel)
            if mm and mm.group(1) in WANTED and mm.group(1) not in found:
                found[mm.group(1)] = m.group(1)

    for name, cp in FALLBACK.items():
        if name in WANTED and name not in found:
            found[name] = cp

    missing = [w for w in WANTED if w not in found]
    if missing:
        sys.stderr.write('warning: not found upstream: %s\n' % ', '.join(missing))

    # keep the upstream "common" rule (font-family/weight/display)
    common = ''
    for selectors, body in re.findall(r'([^{}]+)\{([^}]*)\}', css):
        if 'Font Awesome 6 Free' in body and 'font-family' in body:
            common = '%s{%s}' % (selectors.strip(), body)
            break
    if not common:
        common = ('.fa,.fas,.fa-solid{font-family:"Font Awesome 6 Free";'
                  'font-weight:900;-moz-osx-font-smoothing:grayscale;'
                  '-webkit-font-smoothing:antialiased;'
                  'display:var(--fa-display,inline-block);font-style:normal;'
                  'font-variant:normal;line-height:1;text-rendering:auto}')

    lines = [
        '/* Font Awesome Free 6.5.2 subset - generated by tools/make_fa_subset.py.',
        ' * Contains only the icons this UI uses plus the WOFF2 font they need,',
        ' * because the packaged build cannot fetch anything from the network.',
        ' * License: icons CC BY 4.0, font SIL OFL 1.1, code MIT. */',
        '/* the upstream common rule references these custom properties */',
        ':root{--fa-style-family:"Font Awesome 6 Free";--fa-style:900;'
        '--fa-display:inline-block}',
        '@font-face{font-family:"Font Awesome 6 Free";font-style:normal;'
        'font-weight:900;font-display:block;'
        'src:url("fa-solid-900.woff2") format("woff2")}',
        common,
    ]
    for name in WANTED:
        if name in found:
            lines.append('.fa-%s:before{content:"%s"}' % (name, found[name]))
    lines.append('.fa,.fas,.fa-solid{font-weight:900}')

    io.open(OUT_CSS, 'w', encoding='utf-8', newline='\n').write(
        '\n'.join(lines) + '\n')
    sys.stdout.write('wrote %s (%d icons, %d missing)\n'
                     % (OUT_CSS, len(found), len(missing)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
