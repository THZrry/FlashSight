#!/usr/bin/env python3
"""Generate the icon assets the C++ UI needs: web/icons/icons.css plus
src/ui/icon_tables_gen.hpp.

Why data URIs instead of <img src="/icons/...">: the UI has three backends
(browser/wasm, the WhaleUI desktop engine, and the null test adapter). Only the
browser can load an external URL, and even there ~140 separate requests for
14px glyphs is wasteful. A CSS background-image with an inline data URI works
identically in all three, needs no new DOM API, and ships as one file the
packer already knows how to embed.

Why a generated C++ header as well: the UI has to decide WHICH class to apply,
and that decision (extension -> icon, exact filename -> icon) comes from the
upstream theme's mapping. Reading manifest.json at runtime would mean shipping
and parsing JSON in every backend; a static table costs nothing and keeps the
mapping reproducible from the same source.

Usage:
    python tools/make_lobe_subset.py <lobe-icons-dir>
    python tools/make_file_icons.py <material-icon-theme-pkg>
    python tools/make_icon_css.py

Class naming: .mi (the shared box) plus .mi-lobe-<key> / .mi-file-<icon>.
"""
import base64
import io
import json
import os

OUT_CSS = os.path.join('web', 'icons', 'icons.css')
OUT_HPP = os.path.join('src', 'ui', 'icon_tables_gen.hpp')

HEADER = """/* AUTO-GENERATED by tools/make_icon_css.py - do not edit.
 *
 * Model brand icons: @lobehub/icons-static-svg 1.95.1 (MIT, LobeHub)
 * File type icons:   material-icon-theme 5.39.0 (MIT, Material Extensions)
 *
 * Each icon is inlined as a data URI so the packaged build needs no network
 * and no extra HTTP requests. Regenerate with the three tools/make_*.py scripts.
 */
.mi {
  display: inline-block;
  width: 14px; height: 14px;
  flex: none;
  background-repeat: no-repeat;
  background-position: center;
  background-size: contain;
  vertical-align: -2px;
}
.mi-lg { width: 18px; height: 18px; }
"""

HPP_HEAD = """// AUTO-GENERATED by tools/make_icon_css.py - do not edit.
// Extension / filename -> icon-class tables, derived from the upstream icon
// theme's own mapping (see tools/make_file_icons.py). Committed so the build
// needs no extra generation step; regenerate when the icon sets change.
#pragma once

#include <cstddef>

namespace fs {
namespace ui {
namespace icons {

struct IconMapEntry {
  const char* key;
  const char* icon;
};

"""


def data_uri(raw_bytes):
    return 'data:image/svg+xml;base64,' + base64.b64encode(raw_bytes).decode('ascii')


# A monochrome SVG loaded through CSS background-image does NOT inherit the
# element's color: `currentColor` resolves against the image's own initial
# value (black), and an SVG with no fill at all also paints black. Either way the
# mark disappears on a dark background. So monochrome icons are emitted twice,
# with the ink baked in per theme, and the dark variant is selected by the same
# two mechanisms the rest of the stylesheet uses: an explicit data-mode and the
# system preference when the app has not resolved one yet.
INK_LIGHT_BG = '#2b3242'   # dark ink, for light panels
INK_DARK_BG = '#c9d1d9'    # light ink, for dark panels


def bake_ink(raw, ink):
    """Give every path an explicit fill, replacing currentColor / no fill."""
    t = raw.decode('utf-8')
    t = t.replace('currentColor', ink)
    # A root <svg fill="..."> already covers its paths; only add one when the
    # document carries no fill at all, so brand colours are never overwritten.
    if 'fill=' not in t:
        t = t.replace('<svg ', '<svg fill="%s" ' % ink, 1)
    return t.encode('utf-8')


def is_monochrome(raw):
    t = raw.decode('utf-8')
    if 'currentColor' in t:
        return True
    return 'fill=' not in t


def main():
    rules = []
    dark_rules = []
    counts = {}
    mono_count = 0
    for prefix, d in (('lobe', 'web/icons/lobe'), ('file', 'web/icons/file')):
        if not os.path.isdir(d):
            print('skip (missing): %s' % d)
            continue
        n = 0
        for fn in sorted(os.listdir(d)):
            if not fn.endswith('.svg'):
                continue
            key = fn[:-4]
            path = os.path.join(d, fn)
            raw = io.open(path, 'rb').read()
            cls = '.mi-%s-%s' % (prefix, key)
            if is_monochrome(raw):
                mono_count += 1
                rules.append('%s{background-image:url("%s")}'
                             % (cls, data_uri(bake_ink(raw, INK_LIGHT_BG))))
                dark_rules.append('%s{background-image:url("%s")}'
                                  % (cls, data_uri(bake_ink(raw, INK_DARK_BG))))
            else:
                rules.append('%s{background-image:url("%s")}' % (cls, data_uri(raw)))
            n += 1
        counts[prefix] = n

    body = HEADER + '\n'.join(rules) + '\n'
    if dark_rules:
        # NOTE: these must stay SEPARATE rules. Each carries its own
        # background-image, so they cannot share one declaration block, and a
        # comma-joined list of complete rules ("a{...}, b{...}") is not valid
        # CSS - the parser keeps the first and drops the rest, which is how the
        # icons silently stayed in their light ink on a dark background.
        body += ('\n/* Monochrome marks, re-inked for dark panels (see the note in\n'
                 '   tools/make_icon_css.py: background-image SVGs cannot inherit color). */\n')
        body += '\n'.join('[data-mode="dark"] ' + r for r in dark_rules) + '\n'
        body += ('@media (prefers-color-scheme: dark) {\n'
                 + '\n'.join('  :root:not([data-mode="light"]) ' + r
                             for r in dark_rules)
                 + '\n}\n')
    io.open(OUT_CSS, 'w', encoding='utf-8').write(body)
    print('wrote %s: %s, %d monochrome (%.1f KB)'
          % (OUT_CSS, counts, mono_count, os.path.getsize(OUT_CSS) / 1024.0))

    # ---- C++ tables ----
    fman = os.path.join('web', 'icons', 'file', 'manifest.json')
    lman = os.path.join('web', 'icons', 'lobe', 'manifest.json')
    parts = [HPP_HEAD]
    if os.path.isfile(fman):
        m = json.load(io.open(fman, encoding='utf-8'))
        parts.append(cpp_map('kFileExt', m.get('extensions', {})))
        parts.append('')
        parts.append(cpp_map('kFileName', m.get('names', {})))
        parts.append('')
        parts.append('static const char* const kFolderIcon = "%s";'
                     % m.get('folder', 'folder'))
        parts.append('static const char* const kFolderOpenIcon = "%s";'
                     % m.get('folderOpen', 'folder-open'))
        parts.append('static const char* const kFallbackFileIcon = "%s";'
                     % m.get('fallback', 'file'))
    if os.path.isfile(lman):
        lm = json.load(io.open(lman, encoding='utf-8'))
        parts.append('')
        parts.append(cpp_map('kLobeBrand', {k: k for k in lm}))
    parts.append('')
    parts.append('}  // namespace icons')
    parts.append('}  // namespace ui')
    parts.append('}  // namespace fs')
    parts.append('')
    io.open(OUT_HPP, 'w', encoding='utf-8').write('\n'.join(parts))
    print('wrote %s (%.1f KB)' % (OUT_HPP, os.path.getsize(OUT_HPP) / 1024.0))


def cpp_map(name, mapping):
    out = ['static const IconMapEntry %s[] = {' % name]
    for k in sorted(mapping):
        out.append('    {"%s", "%s"},' % (k.replace('\\', '\\\\').replace('"', '\\"'),
                                          mapping[k]))
    out.append('};')
    out.append('static const size_t %s_count = %d;'
               % (name, len(mapping)))
    return '\n'.join(out)

    # ---- C++ tables ----
    fman = os.path.join('web', 'icons', 'file', 'manifest.json')
    lman = os.path.join('web', 'icons', 'lobe', 'manifest.json')
    parts = [HPP_HEAD]
    if os.path.isfile(fman):
        m = json.load(io.open(fman, encoding='utf-8'))
        parts.append(cpp_map('kFileExt', m.get('extensions', {})))
        parts.append('')
        parts.append(cpp_map('kFileName', m.get('names', {})))
        parts.append('')
        parts.append('static const char* const kFolderIcon = "%s";'
                     % m.get('folder', 'folder'))
        parts.append('static const char* const kFolderOpenIcon = "%s";'
                     % m.get('folderOpen', 'folder-open'))
        parts.append('static const char* const kFallbackFileIcon = "%s";'
                     % m.get('fallback', 'file'))
    if os.path.isfile(lman):
        lm = json.load(io.open(lman, encoding='utf-8'))
        parts.append('')
        parts.append(cpp_map('kLobeBrand', {k: k for k in lm}))
    parts.append('')
    parts.append('}  // namespace icons')
    parts.append('}  // namespace ui')
    parts.append('}  // namespace fs')
    parts.append('')
    io.open(OUT_HPP, 'w', encoding='utf-8').write('\n'.join(parts))
    print('wrote %s (%.1f KB)' % (OUT_HPP, os.path.getsize(OUT_HPP) / 1024.0))


if __name__ == '__main__':
    main()
