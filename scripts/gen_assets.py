#!/usr/bin/env python3
"""Pack web/ assets into a C++ header (byte arrays) for embedding in the exe.

Usage:  python scripts/gen_assets.py [web_dir] [out_header]
Defaults: web_dir=web, out_header=src/ui/ui_assets_gen.hpp
The generated header exposes:
    fs::ui::assets::kFiles  -> vector of {name, mime, data, size}
Run after building the wasm target (fs_ui.js/.wasm) so they get embedded.
"""
import os
import sys

# mime by extension
MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".wasm": "application/wasm",
    ".json": "application/json; charset=utf-8",
    ".png": "image/png",
    ".svg": "image/svg+xml",
}


def c_ident(name: str) -> str:
    out = []
    for ch in name:
        out.append(ch if ch.isalnum() else "_")
    return "".join(out)


def main() -> int:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    web_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "web")
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "src", "ui", "ui_assets_gen.hpp")

    if not os.path.isdir(web_dir):
        print("web dir not found: " + web_dir)
        return 1

    names = sorted(f for f in os.listdir(web_dir)
                   if os.path.isfile(os.path.join(web_dir, f)))
    if not names:
        print("no files in " + web_dir)
        return 1

    lines = []
    lines.append("// AUTO-GENERATED by scripts/gen_assets.py - do not edit.")
    lines.append("// Embedded web assets (served by ui_server).")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstddef>")
    lines.append("#include <cstdint>")
    lines.append("#include <string>")
    lines.append("#include <vector>")
    lines.append("")
    lines.append("namespace fs {")
    lines.append("namespace ui {")
    lines.append("namespace assets {")
    lines.append("")
    lines.append("struct Asset {")
    lines.append("  const char* name;")
    lines.append("  const char* mime;")
    lines.append("  const uint8_t* data;")
    lines.append("  size_t size;")
    lines.append("};")
    lines.append("")

    for n in names:
        p = os.path.join(web_dir, n)
        data = open(p, "rb").read()
        ident = c_ident(n)
        lines.append("static const uint8_t kData_" + ident + "[] = {")
        # 16 bytes per line
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            lines.append("  " + ",".join(str(b) for b in chunk) + ",")
        lines.append("};")
        lines.append("static const size_t kSize_" + ident + " = " + str(len(data)) + ";")
        lines.append("")

    lines.append("static inline const std::vector<Asset>& kFiles() {")
    lines.append("  static const std::vector<Asset> files = {")
    for n in names:
        ext = os.path.splitext(n)[1].lower()
        mime = MIME.get(ext, "application/octet-stream")
        ident = c_ident(n)
        lines.append('      {"' + n + '", "' + mime + '", kData_' + ident +
                     ", kSize_" + ident + "},")
    lines.append("  };")
    lines.append("  return files;")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace assets")
    lines.append("}  // namespace ui")
    lines.append("}  // namespace fs")
    lines.append("")

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote " + out_path + " (" + str(len(names)) + " files, " +
          str(sum(os.path.getsize(os.path.join(web_dir, n)) for n in names)) + " bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
